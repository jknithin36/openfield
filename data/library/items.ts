export function createItems(d: Dates): LibraryItem[] {
  return ROWS.map(([id, name, type, center, ageRange, copies, parts, description], i) => ({
    id,
    slug: id,
    name,
    type,
    center,
    description,
    ageRange,
    loanDays: type === "device" ? DEVICE_DAYS : OTHER_DAYS,
    maxExtensions: 1,
    copies,
    parts,
    archived: false,
    addedAt: d.daysAgo(700 - i * 15),
  }));
}
